export function barcodeSvg(text:string):string {
  if(!/^[\x20-\x7e]{1,100}$/.test(text))throw new Error('条码内容须为1至100个英文字母、数字或ASCII符号，请调整档案编码')
  const codes=[104,...Array.from(text).map(c=>c.charCodeAt(0)-32)]
  codes.push(codes.reduce((sum,c,index)=>sum+c*(index||1),0)%103,106)
  let x=20
  const bars:string[]=[]
  for(const code of codes)for(const [index,width] of Array.from(CODE128_PATTERNS[code]).entries()){
    const w=Number(width)*2
    if(index%2===0)bars.push(`<rect x="${x}" y="10" width="${w}" height="80"/>`)
    x+=w
  }
  const escaped=text.replace(/&/g,'&amp;').replace(/</g,'&lt;').replace(/>/g,'&gt;')
  const svg=`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${x+20} 120" width="${x+20}" height="120"><rect width="100%" height="100%" fill="white"/><g fill="black">${bars.join('')}</g><text x="${(x+20)/2}" y="110" text-anchor="middle" font-family="monospace" font-size="14">${escaped}</text></svg>`
  return 'data:image/svg+xml;charset=utf-8,'+encodeURIComponent(svg)
}